ROUTER_SCRIPT = """<script>
  (function () {
    var supported = __SUPPORTED__;
    var pick = null;
    try { pick = localStorage.getItem(__KEY__); } catch (e) {}
    if (supported.indexOf(pick) < 0) {
      pick = null;
      var prefs = navigator.languages || [navigator.language || ''];
      for (var i = 0; i < prefs.length && !pick; i++) {
        var code = String(prefs[i]).slice(0, 2).toLowerCase();
        if (supported.indexOf(code) >= 0) pick = code;
      }
    }
    location.replace((pick || __DEFAULT__) + '/' + location.hash);
  })();
</script>"""


def router(s, langs):
    script = (
        ROUTER_SCRIPT.replace("__SUPPORTED__", json.dumps(LANG_ORDER))
        .replace("__KEY__", json.dumps(STORAGE_KEY))
        .replace("__DEFAULT__", json.dumps(DEFAULT_LANG))
    )
    head = head_common(
        "Sung Hun Kim, Ph.D. · 김성헌",
        "Sung Hun Kim, Ph.D. — Lead Scientist, SABIC Asia-Pacific. 한국어 · English · 简体中文",
        s["site_url"], "Sung Hun Kim, Ph.D. · 김성헌",
        "Lead Scientist, SABIC Asia-Pacific · Polymer materials technology and global business development",
        "en_US", [l["og_locale"] for l in langs if l["og_locale"] != "en_US"], langs, s, "",
    )
    links = "\n".join(
        f'      <li><a href="{l["code"]}/" lang="{l["hreflang"]}" hreflang="{l["hreflang"]}">{fmt(l["native"])}</a></li>'
        for l in langs
    )
    return f"""<!doctype html>
{NOTICE}
<html lang="en">
<head>
{script}
{head}
</head>
<body>
  <main class="lang-gate">
    <span class="eyebrow">Polymer Materials · Technology &amp; Business Development</span>
    <h1>Sung Hun Kim, Ph.D. <span lang="ko">김성헌</span></h1>
    <ul>
{links}
    </ul>
  </main>
</body>
</html>
"""


def main():
    shared, langs = load()
    for c in langs:
        out = ROOT / c["code"] / "index.html"
        out.parent.mkdir(exist_ok=True)
        out.write_text(page(c, shared, langs), encoding="utf-8", newline="\n")
        print(f"wrote {out.relative_to(ROOT)}")
    (ROOT / "index.html").write_text(router(shared, langs), encoding="utf-8", newline="\n")
    print("wrote index.html")


if __name__ == "__main__":
    main()
