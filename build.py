def fmt(text):
    """Escape text, then apply the content markup: *em*, _{sub}, {ko:...} language spans, newlines."""
    out = html.escape(text, quote=False)
    out = re.sub(r"\{(ko|en|zh-Hans):(.+?)\}", r'<span lang="\1">\2</span>', out)
    out = re.sub(r"\*(.+?)\*", r"<em>\1</em>", out)
    out = re.sub(r"_\{(.+?)\}", r"<sub>\1</sub>", out)
    return out.replace("\n", "<br>")


def attr(text):
    return html.escape(re.sub(r"\{(?:ko|en|zh-Hans):(.+?)\}", r"\1", text), quote=True)


def load():
    shared = tomllib.loads((ROOT / "content" / "shared.toml").read_text(encoding="utf-8"))
    langs = [
        tomllib.loads((ROOT / "content" / f"{code}.toml").read_text(encoding="utf-8"))
        for code in LANG_ORDER
    ]
    return shared, langs


def head_common(title, description, canonical, og_title, og_description, og_locale, locale_alts, langs, s, prefix):
    alternates = "\n".join(
        f'<link rel="alternate" hreflang="{l["hreflang"]}" href="{s["site_url"]}{l["code"]}/">' for l in langs
    )
    locale_meta = "\n".join(f'<meta property="og:locale:alternate" content="{loc}">' for loc in locale_alts)
    return f"""<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{attr(title)}</title>
<meta name="description" content="{attr(description)}">
<meta name="theme-color" content="#0B1420">
<link rel="canonical" href="{canonical}">
{alternates}
<link rel="alternate" hreflang="x-default" href="{s["site_url"]}">
<meta property="og:type" content="profile">
<meta property="og:locale" content="{og_locale}">
{locale_meta}
<meta property="og:title" content="{attr(og_title)}">
<meta property="og:description" content="{attr(og_description)}">
<meta property="og:image" content="{s["site_url"]}assets/portrait.jpg">
<meta property="og:url" content="{canonical}">
<meta name="twitter:card" content="summary">
<link rel="icon" href="{FAVICON}">
<link rel="preconnect" href="https://cdn.jsdelivr.net" crossorigin>
<link rel="stylesheet" href="{PRETENDARD}">
<link rel="stylesheet" href="{prefix}assets/site.css">"""


def lang_menu(c, langs):
    items = []
    for l in langs:
        current = ' aria-current="page"' if l["code"] == c["code"] else ""
        items.append(
            f'          <li><a href="../{l["code"]}/" data-base="../{l["code"]}/" data-lang="{l["code"]}" '
            f'lang="{l["hreflang"]}" hreflang="{l["hreflang"]}"{current}>'
            f'{fmt(l["native"])}<small>{l["label"]}</small></a></li>'
        )
    items_html = "\n".join(items)
    return f"""<details class="lang">
        <summary aria-label="{attr(c["ui"]["lang_aria"])}">{GLOBE}<span>{c["label"]}</span>{CHEVRON}</summary>
        <ul class="lang-menu">
{items_html}
        </ul>
      </details>"""


def section_label(sec):
    intro = f'\n        <p>{fmt(sec["intro"])}</p>' if sec.get("intro") else ""
    return f"""<div class="section-label">
        <span class="eyebrow">{fmt(sec["eyebrow"])}</span>
        <h2>{fmt(sec["title"])}</h2>{intro}
      </div>"""


def render_stats(c):
    items = []
    for st in c["stats"]:
        unit = f'<small>{fmt(st["unit"])}</small>' if st.get("unit") else ""
        items.append(f"""        <li>
          <div class="stat-value num">{fmt(st["value"])}{unit}</div>
          <div class="stat-label">{fmt(st["label"])}</div>
          <div class="stat-note">{fmt(st["note"])}</div>
        </li>""")
    return "\n".join(items)


def render_expertise(c):
    items = []
    for it in c["expertise"]["items"]:
        items.append(f"""        <li>
          <h3>{fmt(it["title"])}</h3>
          <p>{fmt(it["body"])}</p>
          <div class="keys">{fmt(it["keys"])}</div>
        </li>""")
    return "\n".join(items)


def render_career(c):
    orgs = []
    for org in c["career"]["orgs"]:
        roles = []
        for r in org["roles"]:
            cls = "role is-current" if r.get("current") else "role"
            unit = f'\n              <div class="role-unit">{fmt(r["unit"])}</div>' if r.get("unit") else ""
            bullets = "\n".join(f"                <li>{fmt(b)}</li>" for b in r["bullets"])
            roles.append(f"""            <div class="{cls}">
              <div class="role-head"><h4>{fmt(r["title"])}</h4><span class="role-date num">{fmt(r["date"])}</span></div>{unit}
              <ul>
{bullets}
              </ul>
            </div>""")
        roles_html = "\n".join(roles)
        orgs.append(f"""        <article class="org">
          <div class="org-head">
            <div>
              <h3>{fmt(org["name"])}</h3>
              <div class="org-meta">{fmt(org["meta"])}</div>
            </div>
            <div class="org-span num">{fmt(org["span"])}</div>
          </div>
          <div class="roles">
{roles_html}
          </div>
        </article>""")
    return "\n\n".join(orgs)


def render_education(c):
    items = []
    for it in c["education"]["items"]:
        notes = "<br>".join(fmt(n) for n in it["notes"])
        items.append(f"""        <li>
          <div class="edu-year num">{fmt(it["year"])}</div>
          <h3>{fmt(it["degree"])}</h3>
          <div class="edu-inst">{fmt(it["inst"])}</div>
          <div class="edu-thesis">{notes}</div>
        </li>""")
    return "\n".join(items)


def record(year, title, sub, rid, rid_num):
    num = " num" if rid_num else ""
    return f"""            <li>
              <span class="rec-year num">{fmt(year)}</span>
              <div><div class="rec-title">{fmt(title)}</div><div class="rec-sub">{fmt(sub)}</div></div>
              <span class="rec-id{num}">{fmt(rid)}</span>
            </li>"""


def render_research(c, s):
    r = c["research"]
    patents = "\n".join(record(p["year"], p["title"], p["authors"], p["id"], True) for p in s["patents"])
    pubs = "\n".join(
        record(p["year"], p["title"], p["venue"], r["kinds"][p["kind"]], False) for p in s["publications"]
    )
    honors = "\n".join(
        f'              <li><span>{fmt(h["name"])}</span><span class="num">{fmt(h["year"])}</span></li>'
        for h in r["honors"]
    )
    members = "\n".join(f"              <li><span>{fmt(m)}</span></li>" for m in r["members"])
    return f"""<div class="block">
          <div class="block-head"><h3>{fmt(r["patents_title"])}</h3><span>{fmt(r["patents_meta"])}</span></div>
          <ol class="records">
{patents}
          </ol>
        </div>

        <div class="block">
          <div class="block-head"><h3>{fmt(r["pubs_title"])}</h3><span>{fmt(r["pubs_meta"])}</span></div>
          <ol class="records">
{pubs}
          </ol>
        </div>

        <div class="block honors">
          <div>
            <div class="block-head"><h3>{fmt(r["honors_title"])}</h3></div>
            <ul class="plain-list">
{honors}
            </ul>
          </div>
          <div>
            <div class="block-head"><h3>{fmt(r["members_title"])}</h3></div>
            <ul class="plain-list">
{members}
            </ul>
          </div>
        </div>"""


